-- Modelo relacional de referencia para Oracle Database 21c.
-- Ejecute solamente en un esquema de desarrollo o pruebas.

CREATE TABLE backup_database (
    database_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR2(80) NOT NULL,
    service_name      VARCHAR2(180) NOT NULL,
    oracle_version    VARCHAR2(40),
    archive_mode      VARCHAR2(20) NOT NULL CHECK (archive_mode IN ('ARCHIVELOG','NOARCHIVELOG')),
    available_gb      NUMBER(12,2),
    status            VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL CHECK (status IN ('AVAILABLE','UNAVAILABLE')),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_backup_database_name UNIQUE (name)
);

CREATE TABLE backup_strategy (
    strategy_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_id       NUMBER NOT NULL REFERENCES backup_database(database_id),
    name              VARCHAR2(120) NOT NULL,
    description       VARCHAR2(1000),
    responsible       VARCHAR2(120) NOT NULL,
    priority          VARCHAR2(10) NOT NULL CHECK (priority IN ('ALTA','MEDIA','BAJA')),
    status            VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL CHECK (status IN ('ACTIVA','INACTIVA')),
    backup_type       VARCHAR2(30) NOT NULL CHECK (backup_type IN ('FULL','LEVEL_0','LEVEL_1_DIFF','LEVEL_1_CUM')),
    compressed        CHAR(1) DEFAULT 'S' NOT NULL CHECK (compressed IN ('S','N')),
    retention_days    NUMBER(5) DEFAULT 14 NOT NULL CHECK (retention_days > 0),
    channel_count     NUMBER(2) DEFAULT 1 NOT NULL CHECK (channel_count BETWEEN 1 AND 8),
    check_logical     CHAR(1) DEFAULT 'N' NOT NULL CHECK (check_logical IN ('S','N')),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_backup_strategy_name UNIQUE (database_id, name)
);

CREATE TABLE strategy_scope (
    scope_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id        NUMBER NOT NULL REFERENCES backup_strategy(strategy_id) ON DELETE CASCADE,
    object_type        VARCHAR2(20) NOT NULL CHECK (object_type IN ('DATABASE','TABLESPACE','DATAFILE','CONTROLFILE','SPFILE','ARCHIVELOG')),
    object_identifier  VARCHAR2(500),
    CONSTRAINT uq_strategy_scope UNIQUE (strategy_id, object_type, object_identifier)
);

CREATE TABLE strategy_schedule (
    schedule_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id        NUMBER NOT NULL REFERENCES backup_strategy(strategy_id) ON DELETE CASCADE,
    start_at           TIMESTAMP NOT NULL,
    frequency_type     VARCHAR2(20) NOT NULL CHECK (frequency_type IN ('DAILY','WEEKLY','MONTHLY','INTERVAL')),
    execution_days     VARCHAR2(100),
    interval_hours     NUMBER(6),
    window_minutes     NUMBER(6) NOT NULL,
    destination        VARCHAR2(500) NOT NULL,
    enabled            CHAR(1) DEFAULT 'S' NOT NULL CHECK (enabled IN ('S','N')),
    external_job_id    VARCHAR2(200),
    next_run_at        TIMESTAMP
);

CREATE TABLE rman_script (
    script_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id        NUMBER NOT NULL REFERENCES backup_strategy(strategy_id) ON DELETE CASCADE,
    version_number     NUMBER(6) NOT NULL,
    script_text        CLOB NOT NULL,
    sha256             VARCHAR2(64) NOT NULL,
    approval_status    VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL CHECK (approval_status IN ('PENDIENTE','APROBADO','RECHAZADO')),
    approved_by        VARCHAR2(120),
    approved_at        TIMESTAMP,
    created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_rman_script_version UNIQUE (strategy_id, version_number)
);

CREATE TABLE backup_execution (
    execution_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id        NUMBER NOT NULL REFERENCES backup_strategy(strategy_id),
    script_id          NUMBER REFERENCES rman_script(script_id),
    started_at         TIMESTAMP NOT NULL,
    finished_at        TIMESTAMP,
    result             VARCHAR2(20) NOT NULL CHECK (result IN ('EXITO','ADVERTENCIA','FALLO')),
    error_message      VARCHAR2(2000),
    backup_location    VARCHAR2(500),
    rman_output        CLOB,
    backup_file_exists CHAR(1) DEFAULT 'N' NOT NULL CHECK (backup_file_exists IN ('S','N')),
    restore_validated  CHAR(1) DEFAULT 'N' NOT NULL CHECK (restore_validated IN ('S','N')),
    evidence_sha256    VARCHAR2(64),
    created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE preventive_alert (
    alert_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id        NUMBER REFERENCES backup_strategy(strategy_id),
    database_id        NUMBER REFERENCES backup_database(database_id),
    alert_type         VARCHAR2(50) NOT NULL,
    severity           VARCHAR2(15) NOT NULL CHECK (severity IN ('INFO','ADVERTENCIA','CRITICA')),
    message            VARCHAR2(2000) NOT NULL,
    detected_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    status             VARCHAR2(15) DEFAULT 'ABIERTA' NOT NULL CHECK (status IN ('ABIERTA','ATENDIDA','DESCARTADA')),
    resolved_at        TIMESTAMP
);

CREATE INDEX ix_execution_strategy_date ON backup_execution(strategy_id, started_at DESC);
CREATE INDEX ix_alert_status_date ON preventive_alert(status, detected_at DESC);

